INDEX_HEADER = """# 菜谱库

> CookingCoder 的菜谱库：一次初始化，长期维护。每周末从「本周推荐」选一道做。

## 菜谱索引

| 菜名 | 难度 | 耗时 | 口味 | 标签 |
| --- | --- | --- | --- | --- |
{rows}

## 每周推荐轮换

按顺序每周推荐一道（W36 起）：
{weekly}
"""


def build() -> None:
    os.makedirs("recipes", exist_ok=True)
    rows = []
    weekly = []
    for i, r in enumerate(RECIPES, 1):
        fname, title, tags, diff, tm, sv, taste, season, src, desc, ing, steps, tips = r
        tags_str = "[" + ", ".join(f'"{t}"' for t in tags) + "]"
        ing_rows = "\n".join(f"| {n} | {q} | {note} |" for n, q, note in ing)
        step_rows = "\n".join(f"{s}" for s in steps)
        tips_rows = "\n".join(f"- {t}" for t in tips)
        content = TEMPLATE.format(
            title=title, tags=tags_str, difficulty=diff, time=tm,
            servings=sv, taste=taste, season=season, source=src,
            desc=desc, ingredients=ing_rows, steps=step_rows, tips=tips_rows,
        )
        path = os.path.join("recipes", fname)
        with open(path, "w", encoding="utf-8") as f:
            f.write(content)
        rows.append(f"| [{title}]({fname}) | {diff} | {tm} | {taste} | {', '.join(tags)} |")
        weekly.append(f"{i}. {title}")
    index = INDEX_HEADER.format(rows="\n".join(rows), weekly="\n".join(weekly))
    with open(os.path.join("recipes", "_index.md"), "w", encoding="utf-8") as f:
        f.write(index)
    print(f"生成 {len(RECIPES)} 道菜谱 + 索引")


if __name__ == "__main__":
    build()
